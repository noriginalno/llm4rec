def _csv(path: Path, users: list[str], fields: list[str] | None = None) -> Path:
    """Write adversarial fixtures with stdlib CSV, not the production writer."""
    if fields is None:
        fields = ["11 22 33 44 55"] * len(users)
    assert len(fields) == len(users)
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["user_id", "tv_show_id"])
        writer.writerows(zip(users, fields))
    return path


def _json(path: Path, value) -> Path:
    path.write_text(json.dumps(value, ensure_ascii=False), encoding="utf-8")
    return path


def _assert_ranking(result, items, indices, scores, fallback):
    assert isinstance(result, dict)
    assert result["items"] == items
    assert result["indices"] == indices
    assert result["fallback_positions"] == fallback
    assert len(set(result["items"])) == len(items)
    assert len(result["scores"]) == len(scores)
    for actual, expected in zip(result["scores"], scores):
        if expected is None:
            assert actual is None, "Backfill must not masquerade as model evidence"
        else:
            assert actual == pytest.approx(expected)
            assert math.isfinite(actual)


