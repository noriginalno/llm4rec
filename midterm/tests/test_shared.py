def _oracle_cli(submission_path, template_path, allowed_path, *extra):
    # Isolated mode removes the project from import search paths. This succeeds
    # without importing sweettv or needing any third-party package on the CLI.
    return subprocess.run(
        [sys.executable, "-I", "-S", str(ORACLE_PATH), "--submission", str(submission_path),
         "--template", str(template_path), "--allowed-ids", str(allowed_path), *map(str, extra)],
        capture_output=True, text=True, check=False,
    )


def test_independent_cli_csv_and_metric_round_trip(tmp_path):
    users = ["000007", str(MAX_INT64), "18446744073709551615", "u,quoted"]
    allowed = [11, 22, 33, WIDE_ID, MAX_INT64]
    field = " ".join(map(str, allowed))
    submission_path = _csv(tmp_path / "submission.csv", users, [field] * len(users))
    template_path = _csv(tmp_path / "template.csv", users, [""] * len(users))
    allowed_path = _json(tmp_path / "allowed.json", allowed)
    predictions_path = _json(tmp_path / "predictions.json", {
        "slide-1": [11, 22, 44, 33, 55], "slide-2": [44, 11, 55, 22, 33], "cold": [11, 22, 33, 44, 55],
    })
    labels_path = _json(tmp_path / "labels.json", {"slide-1": [11, 22, 33], "slide-2": [11, 22, 33], "cold": []})
    users_path = _json(tmp_path / "users.json", ["cold", "slide-2", "slide-1"])
    process = _oracle_cli(
        submission_path, template_path, allowed_path,
        "--predictions-json", predictions_path, "--labels-json", labels_path, "--users-json", users_path,
    )
    assert process.returncode == 0, process.stderr
    result = json.loads(process.stdout)
    assert result["submission"]["valid"] is True
    assert result["submission"]["user_count"] == 4
    assert result["submission"]["sha256"] == hashlib.sha256(submission_path.read_bytes()).hexdigest()
    assert result["evaluation"]["map_at_5"] == pytest.approx(29 / 60)
    assert result["evaluation"]["precision_at_5"] == pytest.approx(2 / 5)
    assert result["evaluation"]["recall_at_5"] == pytest.approx(2 / 3)


