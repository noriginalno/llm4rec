def test_rank_finite_evidence_precedes_training_popularity_backfill(evaluation):
    item_ids = np.array([900, 20, 100, 7, 55, 41, 3], dtype=np.int64)
    candidates = np.array([2, 0, 6, 3, 4, 1, 5])
    scores = np.array([0.8, -0.2, np.nan, 0.8, np.nan, 0.8, np.nan])
    popularity = np.array([100, 999, 9, 0, 5, 20, 20])
    result = evaluation.rank_candidates(scores, candidates, item_ids, popularity)
    # Tied finite .8: raw 7,20,100; finite -.2 beats every NaN. Then pop20
    # candidates raw 3 and 41 tie, so raw 3 fills the last position.
    _assert_ranking(result, [7, 20, 100, 900, 3], [3, 1, 2, 0, 6], [.8, .8, .8, -.2, None], 1)


def test_rank_all_nan_backfill_is_candidate_only(evaluation):
    item_ids = np.array([1000, 9, 60, 4, 88, 3, 77, 11])
    candidates = np.array([7, 5, 3, 4, 2, 1])
    popularity = np.array([9999, 10, 5, 5, 10, 1, 3, 5])
    result = evaluation.rank_candidates(np.full(6, np.nan), candidates, item_ids, popularity)
    # Globally popular raw 1000 is outside the candidate catalog. Within it:
    # pop10 -> 9,88; pop5 -> 4,11,60. No noncandidate may enter backfill.
    _assert_ranking(result, [9, 88, 4, 11, 60], [1, 4, 3, 7, 2], [None] * 5, 5)


