def test_rank_is_invariant_to_aligned_candidate_order_and_does_not_mutate_inputs(evaluation):
    ids = np.array([90, 8, 60, 3, 50, 2, 70])
    candidates = np.array([4, 0, 6, 2, 1, 3, 5])
    scores = np.array([np.nan, .4, -.5, .4, np.nan, .4, np.nan])
    popularity = np.array([0, 10, 0, 0, 10, 10, 0])
    originals = [array.copy() for array in (ids, candidates, scores, popularity)]
    for permutation in (np.arange(7), np.arange(6, -1, -1), np.array([2, 5, 1, 6, 0, 4, 3])):
        aligned_scores, aligned_candidates = scores[permutation], candidates[permutation]
        score_copy, candidate_copy = aligned_scores.copy(), aligned_candidates.copy()
        result = evaluation.rank_candidates(aligned_scores, aligned_candidates, ids, popularity)
        _assert_ranking(result, [3, 60, 90, 70, 2], [3, 2, 0, 6, 5], [.4, .4, .4, -.5, None], 1)
        np.testing.assert_array_equal(aligned_scores, score_copy)
        np.testing.assert_array_equal(aligned_candidates, candidate_copy)
    for actual, original in zip((ids, candidates, scores, popularity), originals):
        np.testing.assert_array_equal(actual, original)


