def test_rank_infinities_are_rejected_or_consistently_treated_as_unsupported(evaluation):
    policies = []
    for infinity in (np.inf, -np.inf):
        try:
            result = evaluation.rank_candidates(
                np.array([infinity, 4, 3, 2, 1, np.nan]), np.arange(6),
                np.array([99, 10, 20, 30, 40, 50]), np.array([0, 0, 0, 0, 0, 100]),
            )
        except ValueError:
            policies.append("reject")
        else:
            policies.append("unsupported")
            _assert_ranking(result, [10, 20, 30, 40, 50], [1, 2, 3, 4, 5], [4, 3, 2, 1, None], 1)
    assert len(set(policies)) == 1, "Positive/negative infinity must have one consistent policy"


def test_submission_writer_exact_round_trip_with_string_and_int64_ids(submission, independent, tmp_path):
    users = ["000007", str(MAX_INT64), "18446744073709551615", "user,quoted", "u-é"]
    items = [MAX_INT64, WIDE_ID, 11, 22, 33]
    predictions = {user: items[:] for user in reversed(users)}
    path = tmp_path / "new-submission.csv"
    assert isinstance(submission.write_submission(path, users, predictions), dict)
    with path.open(encoding="utf-8", newline="") as stream:
        rows = list(csv.reader(stream, strict=True))
    assert rows[0] == ["user_id", "tv_show_id"]
    assert [row[0] for row in rows[1:]] == users
    assert [row[1] for row in rows[1:]] == [" ".join(map(str, items))] * len(users)
    assert isinstance(submission.validate_submission(path, users, set(items)), dict)
    report = independent.inspect_submission(path, users, set(items))
    assert report["user_count"] == len(users)
    assert report["sha256"] == hashlib.sha256(path.read_bytes()).hexdigest()


