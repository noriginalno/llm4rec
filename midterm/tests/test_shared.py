def test_evaluation_uses_explicit_common_cohort_and_zero_label_users(evaluation):
    users = ["cold", "slide-2", "slide-1"]
    predictions = {
        "slide-1": [11, 22, 44, 33, 55],
        "slide-2": [44, 11, 55, 22, 33],
        "cold": [11, 22, 33, 44, 55],
        "not-in-cohort": [99, 98, 97, 96, 95],
    }
    labels = {"slide-1": [11, 22, 33], "slide-2": [11, 22, 33], "cold": [], "not-in-cohort": [99]}
    result = evaluation.evaluate_predictions(predictions, labels, users)
    # Mean AP = (11/12 + 8/15 + 0) / 3 = 29/60; P = (3/5+3/5+0)/3.
    assert result["map_at_5"] == pytest.approx(29 / 60)
    assert result["precision_at_5"] == pytest.approx(2 / 5)
    assert result["recall_at_5"] == pytest.approx(2 / 3)
    assert result["user_count"] == 3
    records = result["per_user"]
    assert isinstance(records, list)
    assert [row["user_id"] for row in records] == users
    for row, ap, hits, count in zip(records, [0, 8 / 15, 11 / 12], [0, 3, 3], [0, 3, 3]):
        assert row["ap"] == pytest.approx(ap)
        assert row["hits"] == hits
        assert row["relevant_count"] == count
        assert row["precision"] == pytest.approx(hits / 5)
        assert row["recall"] == pytest.approx(hits / count if count else 0)


